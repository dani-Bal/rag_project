class Metadata:
    def __init__(
        self, 
        title=None, 
        author=None, 
        subject=None, 
        keywords=None, 
        pdf_created_at=None, 
        page_count=None, 
        file_size_bytes=None):
            self.title = title
            self.author = author
            self.subject = subject
            self.keywords = keywords
            self.pdf_created_at = pdf_created_at
            self.page_count = page_count
            self.file_size_bytes = file_size_bytes

    
